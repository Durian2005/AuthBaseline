namespace AuthServer.Services;

/**
 * 账号注销时，由**各模块自己**清理挂在账号名下的个人数据。
 *
 * 为什么需要这个接口（而不是让 UserAdminController 直接引用每个模块的 Store）：
 *   注销账号是唯一一处"必须知道所有个人数据都在哪"的地方。若让用户管理控制器
 *   直接 import 每个模块的存储类，那么每加一个生物特征模块，用户管理都要改一次；
 *   反过来，若各模块不登记清理入口，就会出现"账号注销了、模板还留着"的孤儿数据 ——
 *   而生物特征不像口令，删不掉、也换不了。
 *
 * 所以边界这样划：
 *   · 本接口属于**账号域**（谁注销，谁遍历），不认识任何具体模块；
 *   · 具体模块实现它并登记到 DI（见 Program.cs 的 FaceId 注册）；
 *   · 删除顺序由调用方保证：**先清数据、再删账号**（失败则账号不被删除，
 *     从而保证"不会有账号已注销但生物特征还在"这条不变式）。
 *
 * 与 2FA 现有的显式调用并存：那条路径是历史实现，行为已由探针覆盖，
 * 本次不重构它 —— 新模块（FaceId）走接口，避免把两个模块再次绑在一起。
 */
public interface IUserDataPurger
{
    /// <summary>模块名（用于日志/排障时说明是谁清理的）。</summary>
    string Name { get; }

    /// <summary>按用户名清理该模块名下属于此人的全部数据，返回删除条数。</summary>
    Task<long> PurgeByUsernameAsync(string username);
}
